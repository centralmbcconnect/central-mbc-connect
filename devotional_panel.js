const title = document.getElementById("devotional-month-title");
const theme = document.getElementById("devotional-theme");
const scripture = document.getElementById("devotional-monthly-scripture");
const weeksContainer = document.getElementById("devotional-weeks");
const previous = document.getElementById("devotional-previous");
const next = document.getElementById("devotional-next");
let shownMonth = 0;

function renderMonth() {
  const entry = months[shownMonth];
  title.textContent = entry.month + " 2027";
  theme.textContent = "Monthly theme: " + entry.theme;
  scripture.textContent = "Monthly Scripture: " + entry.monthly;
  weeksContainer.replaceChildren();
  entry.weeks.forEach((week, index) => {
    const card = document.createElement("article");
    card.className = "devotional-week";
    const heading = document.createElement("h4");
    heading.textContent = "Week " + (index + 1) + " | " + week[0];
    const passage = document.createElement("p");
    passage.textContent = "Scripture: " + week[1];
    const reflection = document.createElement("p");
    reflection.textContent = "Reflection / action: " + week[2];
    card.append(heading, passage, reflection);
    weeksContainer.append(card);
  });
  previous.disabled = shownMonth === 0;
  next.disabled = shownMonth === months.length - 1;
}
previous.addEventListener("click", () => {
  if (shownMonth > 0) { shownMonth -= 1; renderMonth(); }
});
next.addEventListener("click", () => {
  if (shownMonth < months.length - 1) { shownMonth += 1; renderMonth(); }
});
renderMonth();
